import assert from 'node:assert/strict';
import { existsSync } from 'node:fs';
import { readFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import test from 'node:test';
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'node:zlib';

const root = new URL('../../', import.meta.url);
const tool = new URL('tools/build-style-bundle.mjs', root);
const target = new URL('assets/css/site.css', root);
const files = [
  'base.css', 'sections.css', 'phone.css', 'themes.css', 'player-preview.css',
  'app-preview.css', 'app-settings.css', 'app-song-edit.css', 'app-library.css',
  'app-home.css', 'app-motion.css', 'app-header.css', 'app-theme-transition.css',
  'dsp.css', 'app-glass.css', 'desktop.css', 'motion.css',
];
const sources = () => Promise.all(files.map(file => readFile(new URL('assets/css/' + file, root))));

test('the generated bundle preserves every source byte in the original stylesheet order', async () => {
  assert.ok(existsSync(tool), 'the zero-dependency bundle builder must exist');
  assert.ok(existsSync(target), 'the generated bundle must be checked in');
  const buffers = await sources();
  const expected = Buffer.concat([
    Buffer.from('/* Generated by tools/build-style-bundle.mjs; edit the source stylesheets */\n'),
    ...buffers.flatMap((buffer, index) => [Buffer.from('\n/* Source: assets/css/' + files[index] + ' */\n'), buffer, Buffer.from(index < buffers.length - 1 ? '\n' : '')]),
  ]);
  assert.deepEqual(await readFile(target), expected);
  const { buildStyleBundle } = await import(tool.href);
  assert.deepEqual(await buildStyleBundle(), expected);
});

test('bundling retains all URL references and every local target remains available', async () => {
  const urlPattern = /url\(\s*(?:"((?:\\.|[^"\\])*)"|'((?:\\.|[^'\\])*)'|([^)]*?))\s*\)/g;
  const urls = buffer => [...buffer.toString('utf8').matchAll(urlPattern)].map(match => match[1] ?? match[2] ?? match[3]);
  const buffers = await sources();
  const original = buffers.flatMap(urls);
  assert.deepEqual(urls(await readFile(target)), original);
  assert.ok(original.length > 0, 'the fixture must exercise actual stylesheet URLs');
  for (const reference of original) {
    if (reference.startsWith('#')) continue;
    const resolved = new URL(reference, target);
    if (resolved.protocol === 'file:') assert.ok(existsSync(resolved), 'missing CSS URL: ' + reference);
  }
});

test('the CLI checks freshness and writes exactly the generated bytes to stdout', async () => {
  const checked = spawnSync(process.execPath, [fileURLToPath(tool), '--check']);
  assert.equal(checked.status, 0, checked.stderr.toString());
  const output = spawnSync(process.execPath, [fileURLToPath(tool), '--stdout'], { maxBuffer: 2 * 1024 * 1024 });
  assert.equal(output.status, 0, output.stderr.toString());
  assert.deepEqual(output.stdout, await readFile(target));
});

test('one gzip dictionary reduces transferred bytes compared with the separate sources', async t => {
  const buffers = await sources();
  const separateGzip = buffers.reduce((bytes, buffer) => bytes + gzipSync(buffer).length, 0);
  const bundle = await readFile(target);
  const bundledGzip = gzipSync(bundle).length;
  t.diagnostic(JSON.stringify({ sources: files.length, sourceBytes: buffers.reduce((bytes, buffer) => bytes + buffer.length, 0), bundleBytes: bundle.length, separateGzip, bundledGzip, savedBytes: separateGzip - bundledGzip }));
  assert.ok(bundledGzip < separateGzip, 'the bundle must reduce actual gzip bytes, including its source comments');
});
