#!/usr/bin/env node
import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const startupScriptNames = ['core', 'motion', 'github', 'demos', 'main'];
export const esbuildVersion = '0.28.2';
const root = fileURLToPath(new URL('../', import.meta.url));

function loadEsbuild() {
  try {
    const require = createRequire(process.env.ESBUILD_FROM ? join(resolve(process.env.ESBUILD_FROM), 'noop.js') : import.meta.url);
    return require('esbuild');
  } catch {
    throw new Error('Requires esbuild ' + esbuildVersion + '; use ESBUILD_FROM to point to an existing node_modules directory');
  }
}

export async function buildStartupScripts({ directory = root, check = false, esbuild = loadEsbuild() } = {}) {
  if (esbuild.version !== esbuildVersion) throw new Error('Requires esbuild ' + esbuildVersion + '; found ' + esbuild.version);
  const outputs = [];
  for (const name of startupScriptNames) {
    const sourcePath = 'assets/js/' + name + '.js';
    const targetPath = 'assets/js/' + name + '.min.js';
    const source = await readFile(join(directory, sourcePath), 'utf8');
    const result = await esbuild.transform(source, {
      loader: 'js', charset: 'utf8', legalComments: 'inline',
      minifyWhitespace: true, minifyIdentifiers: false, minifySyntax: false,
      sourcefile: sourcePath,
    });
    if (result.warnings.length) throw new Error(sourcePath + ': ' + result.warnings.map(warning => warning.text).join('; '));
    const bytes = Buffer.from('/* Generated by tools/build-startup-scripts.mjs; edit ' + sourcePath + ' */\n' + result.code);
    outputs.push({ path: targetPath, bytes, sourceBytes: Buffer.byteLength(source) });
  }
  for (const output of outputs) {
    const target = join(directory, output.path);
    if (check) {
      let current;
      try { current = await readFile(target); } catch (error) { if (error.code !== 'ENOENT') throw error; }
      if (!current || !current.equals(output.bytes)) throw new Error(output.path + ' is stale; run node tools/build-startup-scripts.mjs');
    } else await writeFile(target, output.bytes);
  }
  return outputs.map(output => ({ path: output.path, sourceBytes: output.sourceBytes, bytes: output.bytes.length }));
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  if (args.some(arg => arg !== '--check')) throw new Error('Usage: node tools/build-startup-scripts.mjs [--check]');
  buildStartupScripts({ check: args.includes('--check') }).then(report => {
    for (const file of report) console.log(file.path + ': ' + file.sourceBytes + ' -> ' + file.bytes + ' bytes' + (args.includes('--check') ? ' (current)' : ''));
  }).catch(error => { console.error(error.message); process.exitCode = 1; });
}
